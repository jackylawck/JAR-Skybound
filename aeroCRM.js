    // 雙線性插值 (Bilinear Interpolation)
    interpolate(alphaDeg, mach) {
        const a = Math.max(-4.0, Math.min(22.0, alphaDeg));
        const m = Math.max(0.20, Math.min(0.86, mach));

        let ai = 0;
        for (let i = 0; i < this.alphaGrid.length - 1; i++) {
            if (a >= this.alphaGrid[i] && a <= this.alphaGrid[i + 1]) { ai = i; break; }
        }
        let mi = 0;
        for (let j = 0; j < this.machGrid.length - 1; j++) {
            if (m >= this.machGrid[j] && m <= this.machGrid[j + 1]) { mi = j; break; }
        }

        const a0 = this.alphaGrid[ai], a1 = this.alphaGrid[ai + 1];
        const m0 = this.machGrid[mi], m1 = this.machGrid[mi + 1];

        const ta = (a - a0) / (a1 - a0);
        const tm = (m - m0) / (m1 - m0);

        const interpTable = (tbl) => {
            const v00 = tbl[ai][mi], v10 = tbl[ai + 1][mi];
            const v01 = tbl[ai][mi + 1], v11 = tbl[ai + 1][mi + 1];
            const v0 = v00 + (v10 - v00) * ta;
            const v1 = v01 + (v11 - v01) * ta;
            return v0 + (v1 - v0) * tm;
        };

        return {
            CL: interpTable(this.clTable),
            CD: interpTable(this.cdTable),
            Cm: interpTable(this.cmTable)
        };
    }
